#!/usr/bin/env python3
"""Deterministic, arbitrary-precision reference cases for the owned M1 ABI probe.

No target helper is used to calculate expected results. Invalid C division and
out-of-range float-to-integer conversions are excluded, not assigned outcomes.
"""
from __future__ import annotations

import hashlib
import math
import struct

MASK = (1 << 128) - 1
MIN_I128 = -(1 << 127)
MAX_I128 = (1 << 127) - 1
CATEGORIES = ('signed_div', 'signed_mod', 'unsigned_div', 'unsigned_mod',
              'double_to_signed', 'signed_to_double')


def sample(index: int) -> int:
    """Stable corpus without dependence on a platform's PRNG implementation."""
    raw = f'burdettie-m1-compiler-rt-v1/{index}'.encode('ascii')
    return int.from_bytes(hashlib.sha256(raw).digest()[:16], 'big')


def signed(value: int) -> int:
    value &= MASK
    return value if value <= MAX_I128 else value - (1 << 128)


def trunc_divmod(a: int, b: int) -> tuple[int, int]:
    if not (MIN_I128 <= a <= MAX_I128 and MIN_I128 <= b <= MAX_I128):
        raise ValueError('signed input out of range')
    if b == 0 or (a == MIN_I128 and b == -1):
        raise ValueError('undefined signed division is not a test case')
    q = abs(a) // abs(b)
    if (a < 0) != (b < 0):
        q = -q
    return q, a - q * b


def binary64_bits(value: float) -> int:
    return struct.unpack('>Q', struct.pack('>d', value))[0]


def corpus() -> dict:
    unsigned_edges = sorted({0, 1, 2, 3, 7, MASK, MASK - 1,
        *(n for k in (31, 32, 63, 64, 65, 96, 126, 127)
          for n in ((1 << k) - 1, 1 << k, (1 << k) + 1))})
    signed_edges = sorted({MIN_I128, MIN_I128 + 1, MAX_I128, 0,
        *(sign * n for k in (1, 31, 32, 63, 64, 96, 126)
          for n in ((1 << k) - 1, 1 << k, (1 << k) + 1) for sign in (-1, 1))})
    unsigned_inputs = {(a, b) for a in unsigned_edges for b in unsigned_edges if b}
    signed_inputs = {(a, b) for a in signed_edges for b in signed_edges
                     if b and (a, b) != (MIN_I128, -1)}
    for i in range(128):
        a, b = sample(2 * i), sample(2 * i + 1) or 1
        unsigned_inputs.add((a, b))
        sa, sb = signed(a), signed(b) or 1
        if (sa, sb) != (MIN_I128, -1):
            signed_inputs.add((sa, sb))
    u = [(a, b, *divmod(a, b)) for a, b in sorted(unsigned_inputs)]
    s = [(a, b, *trunc_divmod(a, b)) for a, b in sorted(signed_inputs)]
    # Include exact values and tie-to-even neighbors throughout the 128-bit range.
    ints = {MIN_I128, MIN_I128 + 1, MAX_I128, 0, 1, -1}
    for k in (31, 52, 53, 54, 63, 64, 95, 96, 125, 126):
        ulp = 1 << max(0, k - 52)
        for d in (-ulp - 1, -ulp, -ulp // 2, -1, 0, 1, ulp // 2, ulp, ulp + 1):
            for sign in (-1, 1):
                value = sign * ((1 << k) + d)
                if MIN_I128 <= value <= MAX_I128:
                    ints.add(value)
    ints.update(signed(sample(1000 + i)) for i in range(128))
    int_double = [(n, binary64_bits(float(n))) for n in sorted(ints)]
    floats = {binary64_bits(x) for x in (0., -0., 0.25, -0.25, 0.75, -0.75,
        1.5, -1.5, 2.5, -2.5, float(MIN_I128), math.nextafter(float(1 << 127), 0.))}
    for k in (-1074, -1022, -1, 0, 31, 52, 53, 63, 64, 95, 126):
        v = math.ldexp(1.0, k)
        for x in (v, math.nextafter(v, 0.), math.nextafter(v, math.inf)):
            floats.add(binary64_bits(x)); floats.add(binary64_bits(-x))
    for i in range(128):
        n = sample(2000 + i)
        # Finite binary64 values with exponent <= 126, hence inside signed range.
        floats.add(((n >> 127) << 63) | ((n % 1150) << 52) | (n & ((1 << 52) - 1)))
    double_int = []
    for bits in sorted(floats):
        value = struct.unpack('>d', struct.pack('>Q', bits))[0]
        if not math.isfinite(value) or not MIN_I128 <= value < (1 << 127):
            raise ValueError('generated float-to-integer input outside supported range')
        double_int.append((bits, math.trunc(value)))
    return {'signed': s, 'unsigned': u, 'double_to_signed': double_int,
            'signed_to_double': int_double}


def counts(data: dict) -> dict[str, int]:
    return dict(zip(CATEGORIES, (len(data['signed']), len(data['signed']),
        len(data['unsigned']), len(data['unsigned']), len(data['double_to_signed']),
        len(data['signed_to_double']))))


def word(value: int) -> str:
    return f'0x{value:016x}ULL'


def pair(value: int) -> str:
    value &= MASK
    return '{' + word(value >> 64) + ', ' + word(value & ((1 << 64) - 1)) + '}'


def header(data: dict) -> bytes:
    lines = ['/* Generated by m1_compiler_rt_vectors.py; do not edit. */',
             '#ifndef M1_COMPILER_RT_VECTORS_H', '#define M1_COMPILER_RT_VECTORS_H',
             'struct m1_words { m1_u64 high, low; };',
             'struct m1_div_case { struct m1_words a, b, q, r; };',
             'struct m1_from_double { m1_u64 bits; struct m1_words expected; };',
             'struct m1_to_double { struct m1_words input; m1_u64 bits; };']
    for name in ('signed', 'unsigned'):
        lines.append(f'static const struct m1_div_case m1_{name}_cases[] = {{')
        lines.extend('    {' + ', '.join(pair(v) for v in row) + '},' for row in data[name])
        lines.append('};')
    lines.append('static const struct m1_from_double m1_from_double_cases[] = {')
    lines.extend('    {' + word(bits) + ', ' + pair(n) + '},' for bits, n in data['double_to_signed'])
    lines.append('};')
    lines.append('static const struct m1_to_double m1_to_double_cases[] = {')
    lines.extend('    {' + pair(n) + ', ' + word(bits) + '},' for n, bits in data['signed_to_double'])
    lines.extend(['};', '#endif', ''])
    return '\n'.join(lines).encode('ascii')
